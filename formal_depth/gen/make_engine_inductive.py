#!/usr/bin/env python3
"""Write engine_safety_inductive.sv: formal/engine_safety.sv (unchanged
assertions, module renamed) plus harness/engine_safety_strengthen.vh.

    make_engine_inductive.py SNAP/formal/engine_safety.sv OUT.sv
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
if text.count("module engine_safety ") != 1 or not text.rstrip().endswith("endmodule"):
    raise SystemExit("make_engine_inductive: unexpected engine_safety.sv layout")
text = text.replace("module engine_safety ", "module engine_safety_inductive ", 1)
end = text.rstrip().rindex("endmodule")
text = text[:end] + '`include "engine_safety_strengthen.vh"\n' + text[end:]
open(dst, "w").write("// GENERATED by formal_depth/gen/make_engine_inductive.py; do not edit.\n" + text)
